// Regenerates the placeholder list in README.md from the data files.
import fs from 'node:fs';
import { collect } from './src/lib/placeholders.mjs';
const items = JSON.parse(fs.readFileSync('src/data/open-items.json', 'utf8'));
const found = collect(JSON.parse(fs.readFileSync('src/data/connectors.json', 'utf8')));
let md = '## Open items and placeholders\n\nGenerated by `npm run placeholders`. Also visible at `/placeholders/` in the built site.\n\n### Open items\n\n';
for (const o of items) md += `- **${o.title}** (${o.where}): ${o.detail}\n`;
md += `\n### Marked values in \`src/data/connectors.json\` (${found.length})\n\n`;
for (const f of found) md += `- \`${f.path}\`: ${f.text}\n`;
const readme = fs.readFileSync('README.md', 'utf8').split('## Open items and placeholders')[0];
fs.writeFileSync('README.md', readme + md);
